package dev.brahmkshatriya.wasmtime

import kotlin.test.Test
import kotlin.test.assertEquals

class WasmtimeMingwX64Test {
    @Test
    fun loadsAndCallsWasm() {
        val wasm = byteArrayOf(
            0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
            0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01,
            0x7f, 0x03, 0x02, 0x01, 0x00, 0x07, 0x07, 0x01,
            0x03, 0x61, 0x64, 0x64, 0x00, 0x00, 0x0a, 0x09,
            0x01, 0x07, 0x00, 0x20, 0x00, 0x20, 0x01, 0x6a,
            0x0b,
        )
        val randomWasm = byteArrayOf(
            0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
            0x01, 0x07, 0x01, 0x60, 0x02, 0x7f, 0x7f, 0x01, 0x7f,
            0x02, 0x25, 0x01, 0x16,
            0x77, 0x61, 0x73, 0x69, 0x5f, 0x73, 0x6e, 0x61, 0x70, 0x73, 0x68,
            0x6f, 0x74, 0x5f, 0x70, 0x72, 0x65, 0x76, 0x69, 0x65, 0x77, 0x31,
            0x0a, 0x72, 0x61, 0x6e, 0x64, 0x6f, 0x6d, 0x5f, 0x67, 0x65, 0x74,
            0x00, 0x00,
            0x03, 0x02, 0x01, 0x00,
            0x05, 0x03, 0x01, 0x00, 0x01,
            0x07, 0x13, 0x02,
            0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00,
            0x06, 0x72, 0x61, 0x6e, 0x64, 0x6f, 0x6d, 0x00, 0x01,
            0x0a, 0x0a, 0x01, 0x08, 0x00, 0x20, 0x00, 0x20, 0x01, 0x10, 0x00, 0x0b,
        )
        val randomInstance = Wasmtime.load(randomWasm, limits = WasmtimeLimits(fuel = 1_000_000))
        try {
            assertEquals(0, randomInstance.callI32("random", 0, 32))
        } finally {
            randomInstance.close()
        }

        val instance = Wasmtime.load(
            wasm,
            limits = WasmtimeLimits(fuel = 1_000_000),
            storage = WasmtimeStorage(backingPath = "wasmtime-mingw-storage"),
        )
        try {
            assertEquals(42, instance.callI32("add", 20, 22))
        } finally {
            instance.close()
        }
    }
}
